<?php

use App\Livewire\Forms\LoginForm;
use Illuminate\Support\Facades\Session;
use Livewire\Attributes\Layout;
use Livewire\Volt\Component;

new #[Layout('layouts.guest')] class extends Component
{
    public LoginForm $form;

    /**
     * Handle an incoming authentication request.
     */
    public function login(): void
    {
        $this->validate();

        $this->form->authenticate();

        Session::regenerate();

        // Always land on the role-appropriate dashboard — never a stale
        // intended URL left over from a previous (possibly different-role)
        // session, since that can point at a route the new user can't access.
        $this->redirect(route('dashboard', absolute: false), navigate: true);
    }
}; ?>

<div>
    <!-- Session Status -->
    <x-auth-session-status class="mb-4" :status="session('status')" />

    <form wire:submit="login">
        <!-- Email Address -->
        <div>
            <x-input-label for="email" :value="__('Email')" />
            <x-text-input wire:model="form.email" id="email" class="block mt-1 w-full" type="email" name="email" required autofocus autocomplete="username" />
            <x-input-error :messages="$errors->get('form.email')" class="mt-2" />
        </div>

        <!-- Password -->
        <div class="mt-4">
            <x-input-label for="password" :value="__('Password')" />

            <x-text-input wire:model="form.password" id="password" class="block mt-1 w-full"
                            type="password"
                            name="password"
                            required autocomplete="current-password" />

            <x-input-error :messages="$errors->get('form.password')" class="mt-2" />
        </div>

        <!-- Remember Me -->
        <div class="block mt-4">
            <label for="remember" class="inline-flex items-center">
                <input wire:model="form.remember" id="remember" type="checkbox" class="rounded border-brand-border text-teal shadow-sm focus:ring-teal" name="remember">
                <span class="ms-2 text-sm text-brand-slate">{{ __('Remember me') }}</span>
            </label>
        </div>

        <div class="flex items-center justify-end mt-4">
            @if (Route::has('password.request'))
                <a class="underline text-sm text-brand-slate hover:text-charcoal rounded-md focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-teal" href="{{ route('password.request') }}" wire:navigate>
                    {{ __('Forgot your password?') }}
                </a>
            @endif

            <x-primary-button class="ms-3">
                {{ __('Log in') }}
            </x-primary-button>
        </div>
    </form>

    <p class="text-center text-sm text-brand-slate mt-6">
        {{ __("Don't have an account?") }}
        <a href="{{ route('register') }}" wire:navigate class="text-teal hover:underline font-medium">{{ __('Sign up') }}</a>
    </p>

    <p class="text-center text-sm mt-2">
        <a href="{{ url('/') }}" wire:navigate class="text-brand-slate hover:text-charcoal">← {{ __('Back to home') }}</a>
    </p>
</div>
